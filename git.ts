// reachability
// ---------------------------------------------------------------------------------------------

export type ObjectLookup = (oid: string) => GitObject | undefined;

/**
 * Every object reachable from `roots`: commit → tree + parents, tree → entries (gitlinks skipped),
 * tag → its target, blob → nothing. Throws on a missing object unless `allowMissing` is set.
 */
export function collectReachable(
  roots: Iterable<string>,
  lookup: ObjectLookup,
  options: { allowMissing?: boolean } = {},
): Set<string> {
  const seen = new Set<string>();
  const queue: string[] = [];
  for (const root of roots) if (isObjectId(root)) queue.push(root);
  while (queue.length) {
    const oid = queue.pop()!;
    if (seen.has(oid)) continue;
    const object = lookup(oid);
    if (!object) {
      if (options.allowMissing) continue;
      throw new Error(`object ${oid} is missing from the store`);
    }
    seen.add(oid);
    if (object.type === 'commit') {
      const commit = parseCommit(object.data);
      queue.push(commit.tree);
      for (const parent of commit.parents) queue.push(parent);
    } else if (object.type === 'tag') {
      queue.push(parseTag(object.data).object);
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) {
        if (entry.mode === '160000') continue;
        queue.push(entry.oid);
      }
    }
  }
  return seen;
}

/** True when `ancestor` is reachable from `tip` (or equal to it). */
export function isAncestor(lookup: ObjectLookup, ancestor: string, tip: string): boolean {
  if (ancestor === tip) return true;
  const seen = new Set<string>();
  const queue: string[] = [tip];
  while (queue.length) {
    const oid = queue.pop()!;
    if (oid === ancestor) return true;
    if (seen.has(oid)) continue;
    seen.add(oid);
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) queue.push(parent);
  }
  return false;
}

/**
 * The objects a fetch of `wants` must send to a client holding `haves`, with an optional depth
 * limit. Returns the send set plus the shallow/unshallow boundary lines for the response.
 *
 * Depth semantics: generation 0 is the want commits; only commits with generation < depth are
 * sent, with their trees and blobs. A commit is shallow when a parent is missing from the client's
 * post-fetch set; a previously shallow commit whose parents are now all present is unshallow.
 */
/** The objects a client holds, from its haves: reachable, but never past a shallow boundary. */
export function collectHeld(haves: readonly string[], shallowIn: readonly string[], lookup: ObjectLookup): Set<string> {
  const held = new Set<string>();
  const shallowSet = new Set(shallowIn);
  const stack = [...haves];
  while (stack.length > 0) {
    const oid = stack.pop()!;
    if (held.has(oid)) continue;
    const object = lookup(oid);
    if (!object) continue;
    held.add(oid);
    if (object.type === 'commit') {
      // A shallow commit is held; its parents are not, so the walk stops here. Its tree is held
      // either way: a shallow clone still holds the tip's whole tree.
      const commit = parseCommit(object.data);
      stack.push(commit.tree);
      if (shallowSet.has(oid)) continue;
      for (const parent of commit.parents) stack.push(parent);
    } else if (object.type === 'tag') {
      const target = parseTag(object.data).object;
      if (isObjectId(target)) stack.push(target);
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) {
        if (entry.mode !== '160000') stack.push(entry.oid);
      }
    }
  }
  return held;
}

export function computeFetch(
  wants: readonly string[],
  haves: readonly string[],
  shallowIn: readonly string[],
  depth: number | null,
  lookup: ObjectLookup,
): { send: Map<string, GitObject>; shallow: string[]; unshallow: string[] } {
  // What the client already holds: reachable from its haves, but never past a shallow boundary —
  // a shallow commit is held, its parents are not. (That is what makes a deepen work: the client
  // has the tip and says so, yet its parent is still missing and must be sent.)
  const haveSet = collectHeld(haves, shallowIn, lookup);
  const send = new Map<string, GitObject>();
  const addObject = (oid: string): void => {
    const object = lookup(oid);
    if (object && !haveSet.has(oid) && !send.has(oid)) send.set(oid, object);
  };
  // Commit generations from the wants (BFS), so a depth limit cuts whole generations.
  // A want that is a tag object is sent as-is and its peeled commit starts the walk.
  const generations = new Map<string, number>();
  const queue: string[] = [];
  for (const want of wants) {
    if (!isObjectId(want) || generations.has(want)) continue;
    const object = lookup(want);
    if (object && object.type === 'tag') {
      addObject(want);
      const target = peelToCommit(lookup, want);
      if (isObjectId(target) && !generations.has(target)) {
        generations.set(target, 0);
        queue.push(target);
      }
      continue;
    }
    generations.set(want, 0);
    queue.push(want);
  }
  const sentCommits = new Set<string>();
  while (queue.length) {
    const oid = queue.shift()!;
    const gen = generations.get(oid)!;
    if (depth !== null && gen >= depth) continue;
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    sentCommits.add(oid);
    addObject(oid);
    const commit = parseCommit(object.data);
    addObject(commit.tree);
    const tree = lookup(commit.tree);
    if (tree && tree.type === 'tree') {
      for (const entry of parseTree(tree.data)) {
        if (entry.mode === '160000') continue;
        addObject(entry.oid);
        // Nested trees: their entries are added too (a commit's whole tree, one level at a time).
        const sub = lookup(entry.oid);
        if (sub && sub.type === 'tree') {
          const stack: string[] = [entry.oid];
          while (stack.length) {
            const treeOid = stack.pop()!;
            const treeObj = lookup(treeOid);
            if (!treeObj || treeObj.type !== 'tree') continue;
            for (const subEntry of parseTree(treeObj.data)) {
              if (subEntry.mode === '160000') continue;
              addObject(subEntry.oid);
              if (subEntry.mode === '40000') stack.push(subEntry.oid);
            }
          }
        }
      }
    }
    for (const parent of commit.parents) {
      if (!generations.has(parent)) {
        generations.set(parent, gen + 1);
        queue.push(parent);
      }
    }
  }
  if (depth === null) {
    // Full reachability: every object reachable from the wants that the client lacks.
    const wanted = collectReachable(wants, lookup, { allowMissing: true });
    for (const oid of wanted) if (!haveSet.has(oid)) addObject(oid);
  }
  // Boundary lines, from the client's post-fetch object set.
  const postFetch = new Set<string>([...haveSet, ...send.keys()]);
  const shallow: string[] = [];
  const unshallow: string[] = [];
  const boundaryCandidates = new Set<string>([...sentCommits, ...shallowIn]);
  for (const oid of boundaryCandidates) {
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    const parents = parseCommit(object.data).parents;
    const missingParent = parents.some((parent) => !postFetch.has(parent));
    if (missingParent) {
      if (!shallow.includes(oid)) shallow.push(oid);
    } else if (shallowIn.includes(oid)) {
      unshallow.push(oid);
    }
  }
  return { send, shallow, unshallow };
}

/** Peel a tag object to its target commit (following nested tags); returns the commit oid. */
export function peelToCommit(lookup: ObjectLookup, oid: string): string {
  let current = oid;
  for (let hops = 0; hops < 10; hops += 1) {
    const object = lookup(current);
    if (!object) return current;
    if (object.type === 'commit') return current;
    if (object.type === 'tag') {
      current = parseTag(object.data).object;
      continue;
    }
    return current;
  }
  return current;
}
